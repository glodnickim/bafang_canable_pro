// Service worker of the browser (WebUSB) version: lets it start without internet and
// be installed as an app (PWA), e.g. on an Android phone used on the bike.
//
// Network first, so a page opened online always gets the current files (the UI and
// the server modules have to match), and each response refreshes the copy kept here.
// Offline, or when the network does not answer within NETWORK_TIMEOUT_MS, the kept
// copy is served. Everything the app needs is fetched on install, so it works offline
// right after the first visit, before any tab was opened.
'use strict';

// The test site (/test/ on GitHub Pages, same origin) gets its own family name from the
// Pages workflow, so neither site deletes the other's cache.
const CACHE_FAMILY = 'evistdrive-canable';
const CACHE = CACHE_FAMILY + '-v1';
const NETWORK_TIMEOUT_MS = 4000;

// Paths relative to this file (the repository root). The full list is precache.json,
// generated by the Pages workflow from the files actually published, so it cannot fall
// out of step with the UI. Without it (a plain static server) only this minimum is
// fetched up front; anything else is still cached the first time it is loaded online.
const PRECACHE_MINIMUM = ['./', 'index.html', 'manifest.webmanifest', 'ui/', 'ui/index.html'];

async function precacheList() {
    try {
        const response = await fetch('precache.json', { cache: 'reload' });
        if (response.ok) return [...PRECACHE_MINIMUM, ...await response.json()];
    } catch (e) { /* minimum only */ }
    return PRECACHE_MINIMUM;
}

self.addEventListener('install', (event) => {
    event.waitUntil((async () => {
        const cache = await caches.open(CACHE);
        // One by one, so a single missing file does not leave the app uncached.
        await Promise.all((await precacheList()).map(async (path) => {
            try {
                const response = await fetch(new Request(path, { cache: 'reload' }));
                if (response.ok) await cache.put(path, response);
            } catch (e) { /* cached later, when fetched */ }
        }));
        await self.skipWaiting();
    })());
});

self.addEventListener('activate', (event) => {
    event.waitUntil((async () => {
        // Only older versions of this site's own cache: other caches on the origin
        // (the test site, other github.io pages of the same user) are left alone.
        for (const key of await caches.keys())
            if (key.startsWith(CACHE_FAMILY + '-v') && key !== CACHE) await caches.delete(key);
        await self.clients.claim();
    })());
});

self.addEventListener('fetch', (event) => {
    const request = event.request;
    if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
    event.respondWith(networkFirst(request));
});

async function networkFirst(request) {
    const cache = await caches.open(CACHE);
    // The app fetches its modules with cache: 'no-store'; the kept copy is keyed by URL.
    const key = new Request(request.url);
    const network = fetch(request).then((response) => {
        if (response.ok) cache.put(key, response.clone());
        return response;
    });
    network.catch(() => {}); // a late failure after the cache answered is not an error
    const timeout = new Promise((resolve) => setTimeout(resolve, NETWORK_TIMEOUT_MS, null));
    try {
        const response = await Promise.race([network, timeout]);
        if (response) return response;
    } catch (e) { /* offline: fall back to the kept copy */ }
    const cached = await cache.match(key, { ignoreSearch: true });
    if (cached) return cached;
    return network; // nothing kept: wait for the network after all, or fail with it
}
