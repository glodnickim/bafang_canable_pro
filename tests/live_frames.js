'use strict';
const assert = require('assert');
const { createLiveFrames } = require('../ui/webusb/live-frames.js');
const live = createLiveFrames({ recent: 2 });
live.add('RX', '00000002', 1, '01', 1000);
live.add('TX', '00000001', 2, '02 03', 1100);
let s = live.snapshot(1200);
assert.deepStrictEqual(s.recent.map((f) => f.t), [100, 0]);
assert.deepStrictEqual(s.ids.map((f) => f.id), ['00000001', '00000002']);
assert.strictEqual(s.rate, 0);
assert.strictEqual(s.ids[1].changed, false);
live.add('RX', '00000002', 2, '04 05', 1300);
live.add('RX', '00000002', 1, '01', 1400);
s = live.snapshot(1700);
assert.deepStrictEqual(s.recent.map((f) => f.t), [400, 300]);
assert.strictEqual(s.rate, 4);
assert.deepStrictEqual(s.ids[1], { id: '00000002', count: 3, dlc: 1, data: '01', ageMs: 300, changed: true });
assert.strictEqual(live.snapshot(2200).ids[1].changed, false);
live.reset();
for (let i = 0; i < 514; i++) live.add('RX', i.toString(16).padStart(8, '0'), 0, '', i);
s = live.snapshot(1000);
assert.strictEqual(s.ids.length, 512);
assert.strictEqual(s.droppedIds, 2);
assert.strictEqual(s.total, 514);
live.add('RX', '00000000', 0, '', 1001);
assert.strictEqual(live.snapshot(2000).ids[0].count, 2);
live.reset();
s = live.snapshot(3000);
assert.deepStrictEqual(s, { recent: [], ids: [], rate: 0, total: 0, droppedIds: 0 });
live.add('RX', '00000000', 0, '', 4000);
assert.strictEqual(live.snapshot(4000).recent[0].t, 0);
console.log('Live frames tests passed');
